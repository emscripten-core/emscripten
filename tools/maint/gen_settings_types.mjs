// Generate TypeScript ambient declarations for Emscripten compile-time
// settings in `out/settings.d.ts` from `src/settings.js` and
// `src/settings_internal.js`.

import * as fs from 'node:fs';
import * as path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as vm from 'node:vm';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const outFile = path.join(rootDir, 'out', 'settings.d.ts');

// Settings converted to `Set<string>` in `src/utility.ts` (`setLikeSettings`).
const setLikeSettings = new Set([
  'EXPORTED_FUNCTIONS',
  'WASM_EXPORTS',
  'SIDE_MODULE_EXPORTS',
  'INCOMING_MODULE_JS_API',
  'ALL_INCOMING_MODULE_JS_API',
  'EXTRA_INCOMING_JS_API',
  'EXPORTED_RUNTIME_METHODS',
  'WEAK_IMPORTS',
]);

// Settings whose compile-time values can take multiple types (see `tools/settings.py`).
const typeOverrides = {
  EXECUTABLE: 'boolean | number | string',
  MODULARIZE: "boolean | number | 'instance'",
  PTHREAD_POOL_SIZE: 'number | string',
  SEPARATE_DWARF: 'boolean | number | string',
  SUPPORT_LONGJMP: 'boolean | number | string',
};

function getSettingType(name, value) {
  if (Object.hasOwn(typeOverrides, name)) {
    return typeOverrides[name];
  }
  if (setLikeSettings.has(name)) {
    return 'Set<string>';
  }
  if (Array.isArray(value)) {
    return 'string[]';
  }
  switch (typeof value) {
    case 'boolean':
      return 'boolean | number';
    case 'number':
      return 'number';
    case 'string':
      return 'string';
    default:
      throw new Error(`Unsupported setting type for ${name}: ${typeof value}`);
  }
}

const ctx = vm.createContext({});
for (const file of ['src/settings.js', 'src/settings_internal.js']) {
  const fullPath = path.join(rootDir, file);
  vm.runInContext(fs.readFileSync(fullPath, 'utf8'), ctx, {filename: fullPath});
}

const declarations = Object.keys(ctx)
  .sort()
  .map((name) => `  var ${name}: ${getSettingType(name, ctx[name])};`);

const output = [
  '// Auto-generated by tools/maint/gen_settings_types.mjs. DO NOT EDIT.',
  '',
  'declare global {',
  ...declarations,
  '}',
  '',
  'export {};',
  '',
].join('\n');

fs.mkdirSync(path.dirname(outFile), {recursive: true});
if (!fs.existsSync(outFile) || fs.readFileSync(outFile, 'utf8') !== output) {
  fs.writeFileSync(outFile, output, 'utf8');
}
