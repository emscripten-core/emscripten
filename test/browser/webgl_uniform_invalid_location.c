// Tests that calling glUniform*() with a uniform location that is not valid
// for the current program generates GL_INVALID_OPERATION, like it does in
// native OpenGL ES. In particular this covers passing a hardcoded integer
// location without having acquired it from glGetUniformLocation().
// See https://github.com/emscripten-core/emscripten/issues/16367
//
// WebGL represents uniform locations as opaque WebGLUniformLocation objects,
// and silently ignores uniform uploads to a null location, so this error
// needs to be generated by the Emscripten GL library.

#include <assert.h>
#include <stdio.h>
#include <GLES2/gl2.h>
#include <emscripten/html5.h>

static GLuint compile_shader(GLenum type, const char *src) {
  GLuint shader = glCreateShader(type);
  glShaderSource(shader, 1, &src, NULL);
  glCompileShader(shader);
  GLint compiled = 0;
  glGetShaderiv(shader, GL_COMPILE_STATUS, &compiled);
  assert(compiled && "Shader compile failed");
  return shader;
}

static void assert_uniforms(GLuint program, GLint loc_val, GLint loc_num, float x, float y, float z, int num) {
  float val[3] = { -1.f, -1.f, -1.f };
  glGetUniformfv(program, loc_val, val);
  assert(val[0] == x && val[1] == y && val[2] == z);
  GLint n = -1;
  glGetUniformiv(program, loc_num, &n);
  assert(n == num);
  assert(glGetError() == GL_NO_ERROR);
}

int main() {
  EmscriptenWebGLContextAttributes attr;
  emscripten_webgl_init_context_attributes(&attr);
  EMSCRIPTEN_WEBGL_CONTEXT_HANDLE ctx = emscripten_webgl_create_context("#canvas", &attr);
  assert(ctx);
  emscripten_webgl_make_context_current(ctx);

  GLuint vs = compile_shader(GL_VERTEX_SHADER,
    "uniform vec3 u_val;\n"
    "uniform int u_num;\n"
    "void main() { gl_Position = vec4(u_val, float(u_num)); }\n");

  GLuint fs = compile_shader(GL_FRAGMENT_SHADER,
    "precision mediump float;\n"
    "void main() { gl_FragColor = vec4(1.0); }\n");

  GLuint program = glCreateProgram();
  glAttachShader(program, vs);
  glAttachShader(program, fs);
  glLinkProgram(program);

  GLint linked = 0;
  glGetProgramiv(program, GL_LINK_STATUS, &linked);
  assert(linked && "Program link failed");

  glUseProgram(program);
  assert(glGetError() == GL_NO_ERROR);

  const float val[] = { 1.f, 2.f, 3.f };

  // Upload uniforms using a hardcoded integer location, without ever having
  // called glGetUniformLocation(). Such a location is not valid, so the calls
  // must raise GL_INVALID_OPERATION instead of being silently ignored.
  glUniform3f(/*location=*/0, 1.f, 2.f, 3.f);
  assert(glGetError() == GL_INVALID_OPERATION);
  // glGetError() clears the error.
  assert(glGetError() == GL_NO_ERROR);

  glUniform3fv(/*location=*/0, 1, val);
  assert(glGetError() == GL_INVALID_OPERATION);

  glUniform1i(/*location=*/0, 42);
  assert(glGetError() == GL_INVALID_OPERATION);

  // Location -1 is always silently ignored without raising an error.
  glUniform3f(-1, 1.f, 2.f, 3.f);
  glUniform3fv(-1, 1, val);
  glUniform1i(-1, 42);
  assert(glGetError() == GL_NO_ERROR);

  // Uploading via locations acquired from glGetUniformLocation() works.
  GLint loc_val = glGetUniformLocation(program, "u_val");
  GLint loc_num = glGetUniformLocation(program, "u_num");
  assert(loc_val != -1);
  assert(loc_num != -1);
  assert(glGetError() == GL_NO_ERROR);

  // None of the erroneous calls above modified any uniform state.
  assert_uniforms(program, loc_val, loc_num, 0.f, 0.f, 0.f, 0);

  glUniform3fv(loc_val, 1, val);
  glUniform1i(loc_num, 42);
  assert(glGetError() == GL_NO_ERROR);
  assert_uniforms(program, loc_val, loc_num, 1.f, 2.f, 3.f, 42);

  // After uniform locations have been queried, uploading to a location that
  // does not exist in the program still raises GL_INVALID_OPERATION, and
  // leaves the existing uniforms untouched.
  GLint invalid_loc = (loc_val > loc_num ? loc_val : loc_num) + 100;

  glUniform3f(invalid_loc, 4.f, 5.f, 6.f);
  assert(glGetError() == GL_INVALID_OPERATION);

  glUniform3fv(invalid_loc, 1, val);
  assert(glGetError() == GL_INVALID_OPERATION);

  glUniform1i(invalid_loc, 43);
  assert(glGetError() == GL_INVALID_OPERATION);

  glUniform3f(-1, 4.f, 5.f, 6.f);
  assert(glGetError() == GL_NO_ERROR);

  assert_uniforms(program, loc_val, loc_num, 1.f, 2.f, 3.f, 42);

  printf("Test passed!\n");
  return 0;
}
